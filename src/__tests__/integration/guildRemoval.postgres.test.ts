/** Real PostgreSQL tests, opt-in ONLY via scripts/test-guild-removal-db.cjs.
 * No dotenv, Discord login, production data or mocked Prisma delegates.
 */
import type { PrismaClient, Raid } from '@prisma/client';
import { Prisma } from '@prisma/client';
import { Client, Events } from 'discord.js';
import { realpathSync } from 'node:fs';
import { resolve, sep } from 'node:path';

const testUrl = process.env.RAIDPRESENCE_DELETION_TEST_URL;
const postgres = testUrl ? describe : describe.skip;

let db: PrismaClient;
let removal: typeof import('../../services/guildRemoval');
let lifecycle: typeof import('../../services/guildLifecycle');
let entitlement: typeof import('../../services/entitlementService');
let config: typeof import('../../commands/config');
let recurrence: typeof import('../../services/recurringRaidService');

const A = 'synthetic-guild-a';
const B = 'synthetic-guild-b';
const USER = 'synthetic-shared-user';
const payload = () => ({ id: A, name: 'Synthetic Alpha' });

function deferred() {
  let release!: () => void;
  const promise = new Promise<void>((done) => { release = done; });
  return { promise, release };
}

async function snapshot() {
  return {
    guilds: await db.guild.findMany({ orderBy: { id: 'asc' } }),
    teams: await db.team.findMany({ orderBy: { id: 'asc' } }),
    raids: await db.raid.findMany({ orderBy: { id: 'asc' } }),
    attendance: await db.raidAttendance.findMany({ orderBy: { id: 'asc' } }),
    prefs: await db.userPreference.findMany({ orderBy: { id: 'asc' } }),
    rolePrefs: await db.userRolePreference.findMany({ orderBy: { id: 'asc' } }),
    votes: await db.topggVote.findMany({ orderBy: { id: 'asc' } }),
  };
}

async function retainedSnapshot() {
  const all = await snapshot();
  return {
    guilds: all.guilds.filter((row) => row.id === B),
    teams: all.teams.filter((row) => row.guildId === B),
    raids: all.raids.filter((row) => row.guildId === B),
    attendance: all.attendance.filter((row) => row.guildId === B),
    prefs: all.prefs.filter((row) => row.guildId === B),
    rolePrefs: all.rolePrefs.filter((row) => row.guildId === B),
    votes: all.votes,
  };
}

async function expectDeleted() {
  expect(await db.guild.count({ where: { id: A } })).toBe(0);
  expect(await Promise.all([
    db.raid.count({ where: { guildId: A } }),
    db.team.count({ where: { guildId: A } }),
    db.userPreference.count({ where: { guildId: A } }),
    db.userRolePreference.count({ where: { guildId: A } }),
    db.raidAttendance.count({ where: { guildId: A } }),
  ])).toEqual([0, 0, 0, 0, 0]);
}

postgres('guild removal draft — isolated real PostgreSQL', () => {
  beforeAll(async () => {
    const url = new URL(testUrl!);
    if (url.hostname !== '127.0.0.1' || !url.port || url.port === '5432' ||
        !/^\/raidpresence_deletion_test_[a-f0-9]{16}$/.test(url.pathname) ||
        url.search !== '?schema=public' || url.password) {
      throw new Error('Refusing a DB URL not generated by the isolated test runner');
    }
    const expectedDataDir = realpathSync(process.env.RAIDPRESENCE_DELETION_TEST_DATA_DIR!);
    const allowed = resolve(__dirname, '../../../.maestro/raidpresence-data-deletion-20261022/db-runs') + sep;
    if (!expectedDataDir.startsWith(allowed)) throw new Error('Test cluster must be inside the dedicated artifact directory');
    // Dynamic imports AFTER setting the explicit URL: the real singleton is used.
    process.env.DATABASE_URL = testUrl;
    db = (await import('../../database/client')).default;
    const [identity] = await db.$queryRaw<Array<{ directory: string; database: string; address: string }>>`
      SELECT current_setting('data_directory') AS directory, current_database() AS database,
             host(inet_server_addr()) AS address
    `;
    expect(realpathSync(identity.directory)).toBe(expectedDataDir);
    expect(identity.database).toBe(url.pathname.slice(1));
    expect(identity.address).toBe('127.0.0.1');
    removal = await import('../../services/guildRemoval');
    lifecycle = await import('../../services/guildLifecycle');
    entitlement = await import('../../services/entitlementService');
    config = await import('../../commands/config');
    recurrence = await import('../../services/recurringRaidService');
  });

  beforeEach(async () => {
    entitlement.clearTierCache();
    await db.raid.deleteMany();
    await db.guild.deleteMany();
    await db.topggVote.deleteMany();
    for (const guildId of [A, B]) {
      await db.guild.create({ data: {
        id: guildId, name: guildId, language: 'de', timezone: 'Europe/Berlin',
        raidLeaderRoles: 'synthetic-leader-role', archiveChannelId: 'synthetic-archive',
        premiumTier: 'PREMIUM', entitlementId: `synthetic-entitlement-${guildId}`,
        trialStartedAt: new Date('2026-01-01T00:00:00Z'), weeklyRaidCount: 3,
      } });
      await db.team.create({ data: { id: `team-${guildId}`, guildId, name: 'Main', isDefault: true, createdBy: USER } });
      await db.userPreference.create({ data: { guildId, userId: USER, username: 'Synthetic Shared Player', wowClass: 'Mage', wowSpec: 'Fire' } });
      await db.userRolePreference.create({ data: { guildId, userId: USER, roleId: 'synthetic-raider-role', wowClass: 'Mage' } });
    }
    await db.team.create({ data: { id: 'team-a-extra', guildId: A, name: 'Alts', createdBy: USER } });
    for (const [guildId, suffix] of [[A, 'open'], [A, 'archive'], [A, 'template'], [A, 'parent'], [A, 'child'], [B, 'other']]) {
      const raidId = `raid-${suffix}`;
      await db.raid.create({ data: {
        id: raidId, guildId, teamId: suffix === 'template' ? 'team-a-extra' : `team-${guildId}`,
        channelId: 'synthetic-channel', messageId: `synthetic-message-${suffix}`,
        raidDate: new Date('2026-01-01T19:00:00Z'), createdBy: USER,
        description: 'Synthetic notes', roles: 'synthetic-role',
        status: suffix === 'open' ? 'open' : 'closed',
        archivedAt: suffix === 'archive' ? new Date('2026-01-02T00:00:00Z') : null,
        archiveChannelId: suffix === 'archive' ? 'synthetic-archive' : null,
        archiveMessageId: suffix === 'archive' ? 'synthetic-archive-message' : null,
        isTemplate: suffix === 'template', templateName: suffix === 'template' ? 'Synthetic Template' : null,
        recurrenceRule: ['parent', 'child'].includes(suffix) ? 'weekly' : null,
        recurrenceParentId: suffix === 'child' ? 'raid-parent' : null,
        createdFromTemplateId: suffix === 'child' ? 'raid-parent' : null,
        nudgeMessageId: 'synthetic-nudge',
      } });
      await db.raidAttendance.create({ data: {
        raidId, guildId, teamId: `team-${guildId}`, userId: USER, username: 'Synthetic Shared Player',
        optoutReason: 'Synthetic reason', playerNote: 'Synthetic player note', interactedAt: new Date(),
      } });
    }
    await db.topggVote.create({ data: { userId: USER, botId: 'synthetic-bot', type: 'test', query: `guild=${A}` } });
  });

  afterAll(async () => { await db?.$disconnect(); });

  it('covers every current model and checks actual migrated FK rules, including RESTRICT', async () => {
    expect(Prisma.dmmf.datamodel.models.map((model) => model.name).sort()).toEqual([
      'Guild', 'Raid', 'RaidAttendance', 'Team', 'TopggVote', 'UserPreference', 'UserRolePreference',
    ]);
    const constraints = await db.$queryRaw<Array<{ conname: string; confdeltype: string }>>`
      SELECT conname, confdeltype::text FROM pg_constraint
      WHERE contype = 'f' AND connamespace = 'public'::regnamespace ORDER BY conname
    `;
    expect(constraints).toEqual([
      { conname: 'RaidAttendance_raidId_fkey', confdeltype: 'c' },
      { conname: 'RaidAttendance_userId_guildId_fkey', confdeltype: 'r' },
      { conname: 'Raid_guildId_fkey', confdeltype: 'c' },
      { conname: 'Raid_recurrenceParentId_fkey', confdeltype: 'n' },
      { conname: 'Raid_teamId_fkey', confdeltype: 'c' },
      { conname: 'Team_guildId_fkey', confdeltype: 'c' },
      { conname: 'UserPreference_guildId_fkey', confdeltype: 'c' },
      { conname: 'UserRolePreference_guildId_fkey', confdeltype: 'c' },
    ]);
    await expect(db.userPreference.delete({ where: { userId_guildId: { userId: USER, guildId: A } } })).rejects.toMatchObject({ code: 'P2003' });
  });

  it('deletes all six scoped tables and preserves every field in the other guild and shared-user votes', async () => {
    const before = await retainedSnapshot();
    expect(await entitlement.getTier(A)).toBe('PREMIUM');
    const result = await removal.createGuildRemovalDraft().remove(payload());
    expect(result).toEqual({ status: 'deleted', guilds: 1, raids: 5 });
    await expectDeleted();
    expect(await retainedSnapshot()).toEqual(before);
    expect(await entitlement.getTier(A)).toBe('FREE');
  });

  it('a naive Guild delete fails on the actual migrated RESTRICT ordering and keeps every row', async () => {
    const before = await snapshot();
    await expect(db.guild.delete({ where: { id: A } })).rejects.toMatchObject({ code: 'P2003' });
    expect(await snapshot()).toEqual(before);
  });

  it('uses real discord.js GuildDelete routing, including a stale available=false', async () => {
    const client = new Client({ intents: [] });
    const draft = removal.createGuildRemovalDraft();
    const guild = { ...payload(), available: false, channels: { cache: new Map() } };
    client.guilds.cache.set(A, guild as any);
    const pending: Array<Promise<unknown>> = [];
    client.on(Events.GuildDelete, (deleted) => { pending.push(draft.remove(deleted)); });
    (client as any).actions.GuildDelete.handle({ id: A });
    expect(pending).toHaveLength(1);
    await Promise.all(pending);
    await expectDeleted();
    await client.destroy();
  });

  it('real unavailable routing retains every row; reconnect/network events do not authorize deletion', async () => {
    const before = await snapshot();
    const client = new Client({ intents: [] });
    const draft = removal.createGuildRemovalDraft();
    const guild = { ...payload(), available: true, channels: { cache: new Map() } };
    client.guilds.cache.set(A, guild as any);
    let deletes = 0;
    let unavailable = 0;
    client.on(Events.GuildDelete, (deleted) => { deletes++; void draft.remove(deleted); });
    client.on(Events.GuildUnavailable, () => { unavailable++; });
    (client as any).actions.GuildDelete.handle({ id: A, unavailable: true });
    client.emit(Events.ShardReconnecting, 0);
    client.emit(Events.ShardError, new Error('synthetic connection loss'), 0);
    expect({ deletes, unavailable }).toEqual({ deletes: 0, unavailable: 1 });
    expect(await snapshot()).toEqual(before);
    await client.destroy();
  });

  it('never deletes for empty or partial startup caches, even if reconciliation stamps leftAt', async () => {
    const before = await snapshot();
    expect(await lifecycle.reconcileDepartedGuilds([])).toBe(0);
    expect(await snapshot()).toEqual(before);
    expect(await lifecycle.reconcileDepartedGuilds([B])).toBe(1);
    expect(await db.guild.count()).toBe(2);
    expect(await db.raid.count()).toBe(6);
    const marked = await snapshot();
    expect(await removal.createGuildRemovalDraft().remove(payload())).toEqual({ status: 'legacy_retained' });
    expect(await snapshot()).toEqual(marked);
  });

  it('leaves explicitly historical leftAt records and all descendants untouched', async () => {
    await lifecycle.markGuildDeparted(payload());
    const before = await snapshot();
    expect(await removal.createGuildRemovalDraft().remove(payload())).toEqual({ status: 'legacy_retained' });
    expect(await snapshot()).toEqual(before);
  });

  it('makes concurrent duplicate events and unknown guild removals idempotent', async () => {
    const draft = removal.createGuildRemovalDraft();
    const results = await Promise.all([draft.remove(payload()), draft.remove(payload())]);
    expect(results.map((result) => result.status)).toEqual(['deleted', 'absent']);
    expect(await draft.remove({ id: 'synthetic-unknown', name: 'Unknown' })).toEqual({ status: 'absent' });
    await expectDeleted();
  });

  it('drains a running job, skips queued old jobs, and rejects new work during removal', async () => {
    const draft = removal.createGuildRemovalDraft();
    await draft.join(payload());
    const entered = deferred();
    const resume = deferred();
    const running = draft.run(A, async () => {
      entered.release();
      await resume.promise;
      await config.setLanguage(A, 'Synthetic Alpha', 'de');
      return 'completed-before-delete';
    });
    await entered.promise;
    let queuedRan = false;
    const queued = draft.run(A, async () => { queuedRan = true; });
    const deleting = draft.remove(payload());
    expect(await draft.run(A, async () => { throw new Error('must not run'); })).toBeUndefined();
    resume.release();
    expect(await running).toBe('completed-before-delete');
    await queued;
    await deleting;
    expect(queuedRan).toBe(false);
    await expectDeleted();
  });

  it('serializes immediate rejoin behind deletion and ignores replay of the removed Guild object', async () => {
    const draft = removal.createGuildRemovalDraft();
    const oldGuild = payload();
    await draft.join(oldGuild);
    const entered = deferred();
    const resume = deferred();
    const running = draft.run(A, async () => { entered.release(); await resume.promise; });
    await entered.promise;
    const staleConfig = draft.run(A, () => config.setLanguage(A, 'Old installation', 'de'));
    const deleting = draft.remove(oldGuild);
    const joining = draft.join(payload());
    const freshWork = draft.run(A, async () => db.guild.findUnique({ where: { id: A } }));
    resume.release();
    await running;
    expect(await staleConfig).toBeUndefined();
    await deleting;
    await joining;
    const fresh = await freshWork;
    expect(fresh).toMatchObject({ language: 'en', timezone: 'UTC', premiumTier: 'FREE', trialStartedAt: null, entitlementId: null, weeklyRaidCount: 0 });
    expect(await db.raid.count({ where: { guildId: A } })).toBe(0);
    expect(await db.team.count({ where: { guildId: A } })).toBe(0);
    expect(await draft.remove(oldGuild)).toEqual({ status: 'deleted', guilds: 1, raids: 5 });
    expect(await db.guild.findUnique({ where: { id: A } })).toEqual(fresh);
  });

  it('permits unrelated-server jobs while one guild is draining', async () => {
    const draft = removal.createGuildRemovalDraft();
    await draft.join(payload());
    await draft.join({ id: B, name: 'Synthetic Beta' });
    const entered = deferred();
    const resume = deferred();
    const running = draft.run(A, async () => { entered.release(); await resume.promise; });
    await entered.promise;
    const deleting = draft.remove(payload());
    expect(await draft.run(B, async () => 'other-server-continues')).toBe('other-server-continues');
    resume.release();
    await running;
    await deleting;
  });

  it('records the product decision: fresh rejoin makes the existing one-time trial grant eligible again', async () => {
    const draft = removal.createGuildRemovalDraft();
    await draft.remove(payload());
    await draft.join(payload());
    expect(await entitlement.grantTrialIfEligible(A)).toMatchObject({ granted: true, tier: 'PREMIUM' });
  });

  it('rolls back the preceding raid/attendance deletes when the final Guild delete fails', async () => {
    const before = await snapshot();
    await db.$executeRawUnsafe(`CREATE FUNCTION fail_guild_removal() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'synthetic delete failure'; END $$`);
    await db.$executeRawUnsafe(`CREATE TRIGGER fail_guild_removal BEFORE DELETE ON "Guild" FOR EACH ROW EXECUTE FUNCTION fail_guild_removal()`);
    try {
      const draft = removal.createGuildRemovalDraft();
      await draft.join(payload());
      // Join changes only updatedAt/name; use the snapshot after that normal sync.
      const beforeDelete = await snapshot();
      await expect(draft.remove(payload())).rejects.toThrow();
      expect(await snapshot()).toEqual(beforeDelete);
      expect(await draft.run(A, async () => 'unsafe')).toBeUndefined();
      expect((await snapshot()).raids).toEqual(before.raids);
    } finally {
      await db.$executeRawUnsafe('DROP TRIGGER fail_guild_removal ON "Guild"');
      await db.$executeRawUnsafe('DROP FUNCTION fail_guild_removal()');
    }
  });

  it.each(['team', 'recurrence', 'template', 'attendance-in', 'attendance-out', 'attendance-team'])('refuses cross-server %s references without modifying either server', async (kind) => {
    if (kind === 'team') await db.raid.update({ where: { id: 'raid-other' }, data: { teamId: `team-${A}` } });
    if (kind === 'recurrence') await db.raid.update({ where: { id: 'raid-other' }, data: { recurrenceParentId: 'raid-open' } });
    if (kind === 'template') await db.raid.update({ where: { id: 'raid-other' }, data: { createdFromTemplateId: 'raid-template' } });
    if (kind === 'attendance-team') await db.raidAttendance.update({
      where: { raidId_userId: { raidId: 'raid-other', userId: USER } },
      data: { teamId: `team-${A}` },
    });
    if (kind === 'attendance-in' || kind === 'attendance-out') await db.raidAttendance.update({
      where: { raidId_userId: { raidId: kind === 'attendance-in' ? 'raid-open' : 'raid-other', userId: USER } },
      data: { guildId: kind === 'attendance-in' ? B : A },
    });
    const before = await snapshot();
    await expect(removal.createGuildRemovalDraft().remove(payload())).rejects.toBeInstanceOf(removal.GuildRemovalIsolationError);
    expect(await snapshot()).toEqual(before);
  });

  it('real FKs reject late child writes and existing recurring code cannot restart a deleted source', async () => {
    const source = (await db.raid.findUnique({ where: { id: 'raid-parent' } })) as Raid;
    await removal.createGuildRemovalDraft().remove(payload());
    await expect(db.userPreference.create({ data: { guildId: A, userId: 'late', username: 'Synthetic Late' } })).rejects.toMatchObject({ code: 'P2003' });
    await expect(db.team.create({ data: { guildId: A, name: 'Late', createdBy: USER } })).rejects.toMatchObject({ code: 'P2003' });
    expect(await recurrence.createFollowUpRaid({} as Client, source, { mode: 'inherit' })).toEqual({ ok: false, reason: 'series_stopped' });
    await expectDeleted();
  });

  it('demonstrates why activation must wrap current config upserts: an unguarded helper recreates Guild', async () => {
    const draft = removal.createGuildRemovalDraft();
    await draft.join(payload());
    await draft.remove(payload());
    await draft.run(A, () => config.setLanguage(A, 'Synthetic Alpha', 'de'));
    await expectDeleted();
    // Characterization of the existing hazard, NOT a claim runtime is protected.
    await config.setLanguage(A, 'Synthetic Alpha', 'de');
    expect(await db.guild.findUnique({ where: { id: A } })).toMatchObject({ language: 'de' });
  });
});
